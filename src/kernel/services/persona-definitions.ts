import type { PersonaEntry } from '../contracts/persona-entry';

function p(
    id: string,
    name: string,
    personaType: PersonaEntry['personaType'],
    era: PersonaEntry['era'],
    nationality: string,
    field: string,
    description: string,
    systemPrompt: string,
    icon: string,
    color: string,
    category: PersonaEntry['category'],
    extra?: Partial<
        Pick<
            PersonaEntry,
            | 'temperature'
            | 'birthYear'
            | 'deathYear'
            | 'famousWorks'
            | 'quotes'
            | 'biography'
            | 'speakingStyle'
            | 'tags'
        >
    >,
): PersonaEntry {
    return {
        id: `persona-${id}`,
        name,
        personaType,
        era,
        nationality,
        field,
        description,
        systemPrompt,
        temperature: extra?.temperature ?? 0.7,
        icon,
        color,
        category,
        birthYear: extra?.birthYear,
        deathYear: extra?.deathYear,
        famousWorks: extra?.famousWorks,
        quotes: extra?.quotes,
        biography: extra?.biography,
        speakingStyle: extra?.speakingStyle,
        tags: extra?.tags ?? [],
    };
}

